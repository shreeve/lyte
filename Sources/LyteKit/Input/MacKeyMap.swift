import Foundation

/// macOS virtual key code (Carbon kVK_*) → Windows virtual key code.
/// Ported from the moonlight-qt mapping; ANSI layout. Unmapped keys are
/// dropped (media keys, Fn, JIS/ISO extras — deferred to M8).
public enum MacKeyMap {
    public static func windowsVK(forMacKeyCode keyCode: UInt16) -> UInt16? {
        table[keyCode]
    }

    /// Windows VK codes for left/right modifier keys, used by flagsChanged.
    public static let modifierVKs: [UInt16: (vk: UInt16, deviceMask: UInt)] = [
        0x38: (0xA0, 0x0000_0002),   // kVK_Shift        → VK_LSHIFT   / NX_DEVICELSHIFTKEYMASK
        0x3C: (0xA1, 0x0000_0004),   // kVK_RightShift   → VK_RSHIFT
        0x3B: (0xA2, 0x0000_0001),   // kVK_Control      → VK_LCONTROL
        0x3E: (0xA3, 0x0000_2000),   // kVK_RightControl → VK_RCONTROL
        0x3A: (0xA4, 0x0000_0020),   // kVK_Option       → VK_LMENU
        0x3D: (0xA5, 0x0000_0040),   // kVK_RightOption  → VK_RMENU
        0x37: (0x5B, 0x0000_0008),   // kVK_Command      → VK_LWIN
        0x36: (0x5C, 0x0000_0010),   // kVK_RightCommand → VK_RWIN
    ]

    private static let table: [UInt16: UInt16] = [
        // Letters
        0x00: 0x41, 0x0B: 0x42, 0x08: 0x43, 0x02: 0x44, 0x0E: 0x45, 0x03: 0x46,
        0x05: 0x47, 0x04: 0x48, 0x22: 0x49, 0x26: 0x4A, 0x28: 0x4B, 0x25: 0x4C,
        0x2E: 0x4D, 0x2D: 0x4E, 0x1F: 0x4F, 0x23: 0x50, 0x0C: 0x51, 0x0F: 0x52,
        0x01: 0x53, 0x11: 0x54, 0x20: 0x55, 0x09: 0x56, 0x0D: 0x57, 0x07: 0x58,
        0x10: 0x59, 0x06: 0x5A,
        // Digits (top row)
        0x1D: 0x30, 0x12: 0x31, 0x13: 0x32, 0x14: 0x33, 0x15: 0x34, 0x17: 0x35,
        0x16: 0x36, 0x1A: 0x37, 0x1C: 0x38, 0x19: 0x39,
        // Punctuation (VK_OEM_*)
        0x18: 0xBB,  // equals   → VK_OEM_PLUS
        0x1B: 0xBD,  // minus    → VK_OEM_MINUS
        0x21: 0xDB,  // [        → VK_OEM_4
        0x1E: 0xDD,  // ]        → VK_OEM_6
        0x2A: 0xDC,  // backslash→ VK_OEM_5
        0x29: 0xBA,  // ;        → VK_OEM_1
        0x27: 0xDE,  // '        → VK_OEM_7
        0x2B: 0xBC,  // ,        → VK_OEM_COMMA
        0x2F: 0xBE,  // .        → VK_OEM_PERIOD
        0x2C: 0xBF,  // /        → VK_OEM_2
        0x32: 0xC0,  // `        → VK_OEM_3
        // Whitespace / editing
        0x24: 0x0D,  // Return
        0x30: 0x09,  // Tab
        0x31: 0x20,  // Space
        0x33: 0x08,  // Delete (backspace)
        0x35: 0x1B,  // Escape
        0x75: 0x2E,  // Forward Delete
        0x72: 0x2D,  // Help → Insert
        // Modifiers (also handled via flagsChanged, listed for completeness)
        0x38: 0xA0, 0x3C: 0xA1, 0x3B: 0xA2, 0x3E: 0xA3,
        0x3A: 0xA4, 0x3D: 0xA5, 0x37: 0x5B, 0x36: 0x5C,
        0x39: 0x14,  // Caps Lock
        // Navigation
        0x73: 0x24,  // Home
        0x77: 0x23,  // End
        0x74: 0x21,  // Page Up
        0x79: 0x22,  // Page Down
        0x7B: 0x25,  // Left
        0x7C: 0x27,  // Right
        0x7D: 0x28,  // Down
        0x7E: 0x26,  // Up
        // Function keys
        0x7A: 0x70, 0x78: 0x71, 0x63: 0x72, 0x76: 0x73, 0x60: 0x74, 0x61: 0x75,
        0x62: 0x76, 0x64: 0x77, 0x65: 0x78, 0x6D: 0x79, 0x67: 0x7A, 0x6F: 0x7B,
        0x69: 0x7C, 0x6B: 0x7D, 0x71: 0x7E, 0x6A: 0x7F,  // F13-F16
        0x40: 0x80, 0x4F: 0x81, 0x50: 0x82, 0x5A: 0x83,  // F17-F20
        // Keypad
        0x52: 0x60, 0x53: 0x61, 0x54: 0x62, 0x55: 0x63, 0x56: 0x64,
        0x57: 0x65, 0x58: 0x66, 0x59: 0x67, 0x5B: 0x68, 0x5C: 0x69,
        0x43: 0x6A,  // keypad *
        0x45: 0x6B,  // keypad +
        0x4E: 0x6D,  // keypad -
        0x41: 0x6E,  // keypad .
        0x4B: 0x6F,  // keypad /
        0x4C: 0x0D,  // keypad Enter → Return
        0x47: 0x90,  // keypad Clear → Num Lock
    ]
}
